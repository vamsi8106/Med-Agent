#!/usr/bin/env bash
# Turns `terraform output` (deploy/terraform) into a ready overlay:
# deploy/k8s/overlays/aws-generated/ (gitignored), which builds on
# overlays/aws and fills in every <...> placeholder -- images, VPC range,
# certificate, host, model -- plus the External Secrets resources that sync
# medagent-secrets from Secrets Manager. Then prints the image push commands.
#
#   scripts/render_aws_overlay.sh <version>          # e.g. the git sha
#
# Optional environment:
#   TF_OUTPUTS=file.json              read outputs from a file (tests), not terraform
#   LLM_BASE_URL=http://host:8000/v1  a model you host elsewhere in the VPC
#   OTEL_EXPORTER_OTLP_ENDPOINT=...   an OpenTelemetry collector (else no traces)
#   OUT_DIR=...                       write elsewhere (must sit in deploy/k8s/overlays/)
set -euo pipefail

version="${1:?usage: $0 <version>}"
root="$(cd "$(dirname "$0")/.." && pwd)"
out="${OUT_DIR:-$root/deploy/k8s/overlays/aws-generated}"

if [[ -n "${TF_OUTPUTS:-}" ]]; then
  outputs="$(cat "$TF_OUTPUTS")"
else
  outputs="$(terraform -chdir="$root/deploy/terraform" output -json)"
fi
# -e would treat a false value (enable_gpu_model) as an error; fail only on a missing key.
get() { jq -r --arg k "$1" '.[$k].value // (if .[$k].value == false then false else error("missing output: \($k)") end)' <<<"$outputs"; }

env="$(get env)"
region="$(get region)"
registry="$(get registry)"
vpc_cidr="$(get vpc_cidr)"
domain="$(get domain_name)"
certificate="$(get certificate_arn)"
secret="$(get secret_name)"
gpu="$(get enable_gpu_model)"
model="$(get model_name)"
mapfile -t images < <(jq -er '.images.value[]' <<<"$outputs")

# Which model, and whether patient data may leave the account.
components=""
llm_ops=""
if [[ "$gpu" == "true" ]]; then
  components="  - ../../components/vllm"
  llm_ops="      - { op: add, path: /data/LLM_MODEL, value: \"$model\" }"
elif [[ -n "${LLM_BASE_URL:-}" ]]; then
  llm_ops="      - { op: add, path: /data/LLM_BASE_URL, value: \"$LLM_BASE_URL\" }
      - { op: add, path: /data/LLM_MODEL, value: \"$model\" }"
elif [[ "$env" == "demo" ]]; then
  # No model in the VPC: Groq. Production refuses a third-party model unless
  # this flag asserts a data agreement; for a demo it asserts instead that
  # only synthetic patients are entered. Never reuse it with real data.
  llm_ops="      - { op: replace, path: /data/LLM_PROVIDER, value: groq }
      - { op: add, path: /data/ALLOW_EXTERNAL_LLM_WITH_PHI, value: \"true\" }"
  echo "note: demo without a GPU node uses Groq -- synthetic patient data only" >&2
else
  echo "error: env=$env has no model in the VPC: set enable_gpu_model = true, or LLM_BASE_URL" >&2
  exit 1
fi

if [[ -n "${OTEL_EXPORTER_OTLP_ENDPOINT:-}" ]]; then
  otel_op="      - { op: add, path: /data/OTEL_EXPORTER_OTLP_ENDPOINT, value: \"$OTEL_EXPORTER_OTLP_ENDPOINT\" }"
else
  otel_op=""
fi

image_lines=""
for image in "${images[@]}"; do
  image_lines+="  - { name: $image, newName: $registry/$image, newTag: \"$version\" }"$'\n'
done

mkdir -p "$out"
cat >"$out/kustomization.yaml" <<EOF
# Generated by scripts/render_aws_overlay.sh from terraform output -- do not edit.
# Builds on base + components/aws directly (not overlays/aws, whose
# placeholders it would have to undo).
# env=$env region=$region version=$version
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: medagent
resources:
  - ../../base
  - secret-store.yaml
  - external-secret.yaml
components:
  - ../../components/aws
$components
images:
${image_lines}patches:
  - target: { kind: ConfigMap, name: medagent-config }
    patch: |-
      - { op: replace, path: /data/FORWARDED_ALLOW_IPS, value: "$vpc_cidr" }
$llm_ops
$otel_op
  - target: { kind: Ingress, name: medagent }
    patch: |-
      - { op: replace, path: /metadata/annotations/alb.ingress.kubernetes.io~1certificate-arn, value: "$certificate" }
      - { op: replace, path: /spec/rules/0/host, value: "$domain" }
EOF

# Namespaced on purpose (kustomize would stamp a namespace on a cluster-scoped
# store). The operator authenticates with its Pod Identity role, which may
# read only this secret (deploy/terraform/addons.tf).
cat >"$out/secret-store.yaml" <<EOF
apiVersion: external-secrets.io/v1
kind: SecretStore
metadata:
  name: aws-secrets-manager
spec:
  provider:
    aws:
      service: SecretsManager
      region: $region
EOF

cat >"$out/external-secret.yaml" <<EOF
apiVersion: external-secrets.io/v1
kind: ExternalSecret
metadata:
  name: medagent-secrets
spec:
  refreshInterval: 1h
  secretStoreRef:
    kind: SecretStore
    name: aws-secrets-manager
  target:
    name: medagent-secrets
  dataFrom:
    - extract:
        key: $secret
EOF

echo "wrote $out" >&2
cat <<EOF

# Build and push the images ($version):
aws ecr get-login-password --region $region | docker login --username AWS --password-stdin $registry
docker compose build ${images[*]}
for image in ${images[*]}; do
  docker tag "medagent-\$image:latest" "$registry/\$image:$version"
  docker push "$registry/\$image:$version"
done

# Then deploy:
kubectl apply -k deploy/k8s/overlays/aws-generated
EOF
